"""The operator's model allowlist: aliases in, exact omp selectors out.

Hermes can never name a model id, URL, provider or env var — only an alias from bridge.toml. The bridge
resolves the alias (explicit on the call, the agent's own default, then [models].default), renders ONE
models.yml holding every enabled alias, and uploads it to the worker's persistent agent dir when the
rendered content changes (tracked by sha256). The rendered file and every log line carry env var NAMES
only; the values are injected inside the sandbox by the OpenShell provider.
"""
import hashlib
import json
import logging

log = logging.getLogger("bridge.models")


class ModelError(Exception):
    """A model alias problem worth reporting to the caller. `code` is machine-readable."""

    def __init__(self, code, message):
        super().__init__(message)
        self.code, self.message = code, message


def resolve(aliases, agent_default, global_default, requested=None):
    """The alias to run, in precedence order: explicit call, the agent's default, the global default.
    Raises ModelError(unknown_model) for a name that is not an enabled alias."""
    name = requested if requested is not None else (agent_default or global_default)
    if name not in aliases:
        valid = sorted(key for key, alias in aliases.items() if alias.enabled)
        raise ModelError("unknown_model",
                         f"model alias {name!r} is not in the allowlist; valid aliases: {', '.join(valid) or '(none)'}")
    alias = aliases[name]
    if not alias.enabled:
        valid = sorted(key for key, other in aliases.items() if other.enabled)
        raise ModelError("unknown_model",
                         f"model alias {name!r} is disabled; valid aliases: {', '.join(valid) or '(none)'}")
    return alias


def render_models_yml(aliases):
    """One models.yml for every enabled alias, grouped by provider id (config enforces unique providers).

    The declared model is always explicit, never discovered, because the worker's provider profile forbids the discovery call.
    """
    q = json.dumps
    lines = ["# generated by omp-bridge: do not edit inside the sandbox", "providers:"]
    for name in sorted(aliases):
        alias = aliases[name]
        if not alias.enabled:
            continue
        auth = "    auth: none" if not alias.api_key_env else f"    apiKey: {alias.api_key_env}"
        lines += [f"  {alias.provider}:", f"    baseUrl: {q(alias.base_url)}", auth,
                  f"    api: {alias.api}", "    models:", f"      - id: {q(alias.model_id)}",
                  f"        name: {q(alias.model_id)}", f"        contextWindow: {int(alias.context_window)}",
                  f"        maxTokens: {int(alias.max_tokens)}"]
    return "\n".join(lines) + "\n"


def models_yml_digest(aliases):
    return hashlib.sha256(render_models_yml(aliases).encode("utf-8")).hexdigest()


class ModelSyncer:
    """Renders and uploads models.yml when the enabled set changes (hash in sqlite)."""

    def __init__(self, cfg, store, shell):
        self.cfg, self.store, self.shell = cfg, store, shell

    def ensure(self):
        """Upload models.yml when its content changed since the last successful upload. Returns the digest."""
        digest = models_yml_digest(self.cfg.aliases)
        if self.store.models_yml_hash() == digest:
            return digest
        self._upload(digest)
        return digest

    def refresh(self):
        """Force the upload (worker volume may have been recreated)."""
        digest = models_yml_digest(self.cfg.aliases)
        self._upload(digest)
        return digest

    def _upload(self, digest):
        import os
        import tempfile
        with tempfile.NamedTemporaryFile("w", suffix=".models.yml", delete=False) as handle:
            handle.write(render_models_yml(self.cfg.aliases))
            local = handle.name
        try:
            self.shell.upload(local, "/sandbox/.omp-agent/models.yml")
        except Exception:
            log.warning("models.yml upload failed", exc_info=True)
            raise
        finally:
            os.unlink(local)
        self.store.set_models_yml_hash(digest)
        log.info("models.yml uploaded (sha256=%s, aliases=%s)", digest[:12],
                 ",".join(sorted(name for name, alias in self.cfg.aliases.items() if alias.enabled)))
